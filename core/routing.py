"""
Единый роутинг сложности запроса: один источник правды для голоса
(main.py) и remote (remote_server.py), чтобы один и тот же вопрос
не маршрутизировался в разные модели разными каналами.
"""

COMPLEX_KEYWORDS = [
    "объясни", "расскажи подробно", "почему", "зачем",
    "сравни", "проанализируй", "напиши", "сочини",
    "придумай", "переведи", "объясни как",
    "квантов", "философ", "история", "наука",
    "стих", "рассказ", "эссе", "сочинение",
]


def is_complex_fast(text):
    text_lower = text.lower()
    if any(kw in text_lower for kw in COMPLEX_KEYWORDS):
        return True
    return len(text_lower.split()) > 15
