_last_joke_index = -1
_last_fact_index = -1


def get_joke():
    """Возвращает случайный анекдот (не повторяя предыдущий)"""
    global _last_joke_index
    idx = random.randint(0, len(JOKES) - 1)
    while idx == _last_joke_index and len(JOKES) > 1:
        idx = random.randint(0, len(JOKES) - 1)
    _last_joke_index = idx
    log.info(f"Анекдот #{idx + 1}")
    return JOKES[idx]


def get_fact():
    """Возвращает случайный факт (не повторяя предыдущий)"""
